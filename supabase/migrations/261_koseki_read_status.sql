-- 戸籍請求の読込結果ステータス。
--
-- 「出生から死亡まで」で請求しても、転籍を最後まで遡れず一部しか取れないことがある。
-- 届いた封筒を受信簿で紐づけた時点では中を読んでいないので判定できず、
-- 戸籍の内容確認タスクを開いた人が初めて気づく。そこで実務タブ（戸籍カード）の
-- 読込結果に、取得完了か一部不足かを残せるようにする。
--
-- 一部不足なら、残りは「＋ 請求を追加」で新しい請求行を作って取りに行く。
-- 請求範囲（range_text）は書き換えない。何を請求したかの記録が消えてしまうため。
--
-- 値: '取得完了' | '一部不足'（NULL＝まだ読んでいない）
alter table koseki_requests add column if not exists read_status text;

comment on column koseki_requests.read_status is
  '読込結果のステータス。取得完了 / 一部不足。NULLは未確認。一部不足の残りは追加請求の行を別に作る';
