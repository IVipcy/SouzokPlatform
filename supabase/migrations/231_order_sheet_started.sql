-- ============================================================
-- 231_order_sheet_started.sql
-- オーダーシートの作成を始めた印。
--
-- 受注より前（面談設定済・検討中・依頼確定待ち）の案件は、案件詳細のオーダーシートの位置に
-- 「面談シート」を出す。面談で聞き取った内容が案件詳細から辿れないままだったため。
-- 「オーダーシートを作成」を押した時点でこの列に日時を入れ、次からはオーダーシートで開く。
-- （押した状態を覚えないと、開くたびに面談シートへ戻って毎回押し直すことになる）
--
-- 受注以降のステータスでは、この列に関係なくオーダーシートを出す。
-- ============================================================

ALTER TABLE cases ADD COLUMN IF NOT EXISTS order_sheet_started_at timestamptz;

COMMENT ON COLUMN cases.order_sheet_started_at IS
  'オーダーシートの作成を開始した日時。受注前の案件で、面談シート／オーダーシートのどちらを出すかの判定に使う。';

NOTIFY pgrst, 'reload schema';
